// DEMO-ONLY (TODO(T-001)). Makes `pnpm demo:up` work on a machine where 5432 is already taken (a system Postgres is
// common): it publishes the demo's Postgres on a free loopback port through a generated compose override in demo/.out.
import { mkdirSync, writeFileSync } from 'node:fs';
import { createServer } from 'node:net';
import { OUT_DIR } from './config.ts';

/** Where the generated override lives. `composeFileArgs()` adds it when it exists. */
export const PORT_OVERRIDE_PATH = `${OUT_DIR}/compose.ports.yml`;

/** True when nothing is listening on 127.0.0.1:`port` and the port can be bound. */
export function isPortFree(port: number): Promise<boolean> {
  return new Promise((resolve) => {
    const server = createServer();
    server.once('error', () => {
      resolve(false);
    });
    server.listen(port, '127.0.0.1', () => {
      server.close(() => {
        resolve(true);
      });
    });
  });
}

/** Asks the OS for a free loopback port. */
export function pickFreePort(): Promise<number> {
  return new Promise((resolve, reject) => {
    const server = createServer();
    server.once('error', reject);
    server.listen(0, '127.0.0.1', () => {
      const address = server.address();
      const port = typeof address === 'object' && address ? address.port : 0;
      server.close(() => {
        if (port > 0) resolve(port);
        else reject(new Error('could not find a free port'));
      });
    });
  });
}

/** The compose override text that publishes Postgres on `port` (loopback only). */
export function portOverrideYaml(port: number): string {
  return [
    '# DEMO-ONLY, generated by `pnpm demo:up` because the default Postgres port was busy. Safe to delete.',
    'services:',
    '  postgres:',
    `    ports: !override ['127.0.0.1:${String(port)}:5432']`,
    '',
  ].join('\n');
}

/** Writes the override for `port` and returns its path. */
export function writePortOverride(port: number, path = PORT_OVERRIDE_PATH): string {
  mkdirSync(path.slice(0, path.lastIndexOf('/')), { recursive: true });
  writeFileSync(path, portOverrideYaml(port), { encoding: 'utf8' });
  return path;
}
